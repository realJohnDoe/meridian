#!/usr/bin/env node
// The daily dispatcher's plan: which findings to start, which PRs need a follow-up
// session, and the twice-weekly digest. See docs/agents/daily-dispatch.md.
// Usage: node scripts/workshop-dispatch.mjs [--apply] [--max-sessions N] [--max-followups N] [--today YYYY-MM-DD] [--followups-only]
// Without --apply it is a dry run: it prints the plan and writes nothing.
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync } from "node:fs";
import { bodyBlockers } from "./bodyBlockers.mjs";

const REPO = "realJohnDoe/meridian";
const arg = (name, dflt) => {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : dflt;
};
const APPLY = process.argv.includes("--apply");
const FOLLOWUPS_ONLY = process.argv.includes("--followups-only"); // drain: merge and follow up, start nothing new
const MAX_SESSIONS = Number(arg("--max-sessions", 4));
const MAX_FOLLOWUPS = Number(arg("--max-followups", 2));
const STALE_DAYS = 2; // a claim or follow-up with nothing to show after this is stuck
// The digest is published on the first run of the day after each survey start
// (the "Start Top-Ranked Survey" task runs Mon and Thu), so each one carries
// that survey's findings. Keep in step with that task's schedule.
const DIGEST_WEEKDAYS = [2, 5]; // Tue, Fri (UTC getDay)
const DIGEST_DAYS = 2.5; // minimum window, so a second run that day doesn't publish again
const TODAY = new Date(arg("--today", new Date().toISOString().slice(0, 10)));
// When this run's digest window ends; a new digest's window starts here.
const NOW = arg("--today") ? TODAY.toISOString() : new Date().toISOString();
const DIGEST_PREFIX = "Workshop digest";
const DISPATCH = "<!-- workshop-dispatch -->";
const FOLLOWUP = "<!-- workshop-followup -->";
const RELAYED = "<!-- workshop-relayed -->"; // digest replies up to here are copied to their issues
// Comments written before the farm → workshop rename still carry `farm-` markers.
const marked = (c, m) =>
  c.body.includes(m) || c.body.includes(m.replace("workshop", "farm"));
// The one merge policy: a green, quiet PR with this label is merged; any other
// non-draft PR waits for review. Whoever opens the PR decides.
const AUTOMERGE = "automerge";
const HELD = ["decision-required", "deferred"];
const SURVEY_LABELS = readdirSync(".claude/skills")
  .filter((d) => d.startsWith("survey-"))
  .map(
    (d) =>
      readFileSync(`.claude/skills/${d}/SKILL.md`, "utf8").match(
        /^label:\s*(\S+)/m,
      )?.[1],
  )
  .filter(Boolean);
const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
const AGENT = /Generated by \[Claude Code\]/;
const TIERS = ["haiku", "sonnet", "opus"];

const api = (path, ...rest) =>
  JSON.parse(
    execFileSync("gh", ["api", path, ...rest], {
      encoding: "utf8",
      maxBuffer: 1 << 26,
    }) || "null",
  );
// --paginate --slurp yields one array per page.
const all = (path) => api(path, "--paginate", "--slurp").flat();
const post = (path, body, method = "POST") =>
  execFileSync("gh", ["api", "-X", method, path, "--input", "-"], {
    input: JSON.stringify(body),
    // Keep gh's stderr out of the log: a failure still throws with it
    // attached, and the expected "already exists" 422 stays quiet.
    stdio: ["pipe", "pipe", "pipe"],
  });
const days = (iso) => (TODAY - new Date(iso)) / 864e5;
const names = (x) => x.labels.map((l) => l.name);
const tierOf = (labels) => labels.find((l) => TIERS.includes(l));

const issues = all(`repos/${REPO}/issues?state=open&per_page=100`).filter(
  (i) => !i.pull_request,
);
const prs = all(`repos/${REPO}/pulls?state=open&per_page=100`);
const byNumber = new Map(issues.map((i) => [i.number, i]));
const linkedIssues = (pr) =>
  [
    ...(pr.body ?? "").matchAll(
      /\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+#(\d+)/gi,
    ),
  ].map((m) => Number(m[1]));
const linked = new Set(prs.flatMap(linkedIssues));
// Open issues an issue waits on: native blocked-by edges, plus the documented
// fallback of a blocker named in the body while it is open.
const blockersOf = new Map(
  issues.map((i) => [
    i.number,
    new Set([
      ...(i.issue_dependencies_summary?.blocked_by > 0
        ? all(
            `repos/${REPO}/issues/${i.number}/dependencies/blocked_by?per_page=100`,
          )
            .filter((b) => b.state === "open")
            .map((b) => b.number)
        : []),
      ...bodyBlockers(i.body).filter((n) => byNumber.has(n)),
    ]),
  ]),
);
const blockedText = (n) =>
  `blocked by ${[...blockersOf.get(n)].map((b) => `#${b}`).join(", ")}`;

// --- PR follow-up -----------------------------------------------------------
// Ours to follow up: every non-draft PR (draft = keep out of the workshop).
const followups = [];
const review = [];
const unstick = [];
const automerge = [];
const isDependabot = (pr) => pr.user.login === "dependabot[bot]";
for (const pr of prs.filter((p) => !p.draft)) {
  const issue = linkedIssues(pr)
    .map((n) => byNumber.get(n))
    .find((i) => i && tierOf(names(i)));
  const bot = isDependabot(pr);
  // A red bump is undiagnosed and often rooted in a dependency's own change.
  const tier = issue ? tierOf(names(issue)) : bot ? "opus" : "sonnet";
  // Dependabot's policy is native auto-merge (dependabot-automerge.yml).
  const auto = names(pr).includes(AUTOMERGE);
  const head = api(`repos/${REPO}/commits/${pr.head.sha}`);
  const headDate = head.commit.committer.date;
  const runs = api(
    `repos/${REPO}/commits/${pr.head.sha}/check-runs?per_page=100`,
  ).check_runs;
  // GitHub runs no CI on a conflicting PR, so this check must not wait for CI.
  // `mergeable` is computed lazily: null means look again next run, not conflict.
  const conflict = api(`repos/${REPO}/pulls/${pr.number}`).mergeable === false;
  const finished =
    runs.length > 0 && runs.every((r) => r.status === "completed");
  if (!finished && !conflict) continue;
  const failing = finished
    ? runs.filter((r) =>
        ["failure", "timed_out", "startup_failure"].includes(r.conclusion),
      )
    : [];
  const comments = all(
    `repos/${REPO}/issues/${pr.number}/comments?per_page=100`,
  );
  const feedback = [
    ...comments,
    ...all(`repos/${REPO}/pulls/${pr.number}/comments?per_page=100`),
    ...all(`repos/${REPO}/pulls/${pr.number}/reviews?per_page=100`).filter(
      (r) => r.body || r.state === "CHANGES_REQUESTED",
    ),
  ].filter(
    (c) =>
      new Date(c.created_at ?? c.submitted_at) > new Date(headDate) &&
      c.user.type !== "Bot" &&
      !AGENT.test(c.body ?? ""),
  );
  if (failing.length === 0 && feedback.length === 0 && !conflict) {
    // dependabot-automerge.yml queues all but majors, and drops a PR anyone else
    // pushed to; those wait for a human.
    if (bot ? !pr.auto_merge : !auto)
      review.push({ pr: pr.number, title: pr.title, url: pr.html_url });
    else if (!pr.auto_merge)
      automerge.push({ pr: pr.number, sha: pr.head.sha, title: pr.title });
    continue;
  }
  const marks = comments.filter((c) => marked(c, FOLLOWUP));
  const last = marks.at(-1);
  const pending = last && new Date(last.created_at) > new Date(headDate);
  if (
    marks.length >= MAX_FOLLOWUPS ||
    (pending && days(last.created_at) > STALE_DAYS)
  ) {
    unstick.push({
      pr: pr.number,
      title: pr.title,
      url: pr.html_url,
      why: `${conflict ? "conflicts with main" : failing.length ? "CI red" : "unanswered review"} after ${marks.length} follow-up(s)`,
    });
    continue;
  }
  if (pending) continue; // a follow-up session is still on it
  followups.push({
    kind: "followup",
    pr: pr.number,
    issue: issue?.number,
    tier,
    branch: pr.head.ref,
    title: `Follow up #${pr.number}`,
    prompt: [
      `PR #${pr.number} (${pr.html_url}, branch \`${pr.head.ref}\`) ${issue ? `for #${issue.number} ` : ""}needs a narrow fix. Work on that branch and push to it; do not open a new PR.`,
      ...(conflict
        ? [
            `- Merge conflict with main: merge or rebase \`main\` into the branch, resolve the conflicts and push. This is a conflict resolution, not a CI fix; CI runs once it pushes.`,
          ]
        : []),
      ...failing.map((r) => `- CI failing: ${r.name}: ${r.html_url}`),
      ...feedback.map((c) => `- Unanswered review feedback: ${c.html_url}`),
      `Fix only that. For CI, reproduce the failure first and show the same check passing. Run \`pnpm run build\` and \`pnpm run lint\` before pushing. Reply to each review comment you address.`,
      bot
        ? `This is a Dependabot bump: adapt the code or config to the new versions rather than reverting a bump, and leave the PR description as Dependabot wrote it. If a bump can't be adopted narrowly, say why in a PR comment instead of pushing.`
        : `The PR description must still meet .github/pull_request_template.md.`,
      `Do not subscribe to PR activity: the daily dispatcher checks this PR again tomorrow.`,
    ].join("\n"),
  });
}

// --- Dispatch ---------------------------------------------------------------
// Why an open issue isn't dispatched: undefined = dispatchable, null = shown
// elsewhere (its PR, the Decide list, the Unstick check, the digest itself).
const isDigest = (i) => /^(Workshop|Farm) digest/.test(i.title);
const skip = (i) => {
  const l = names(i);
  if (isDigest(i) || i.sub_issues_summary?.total > 0) return null;
  if (linked.has(i.number) || l.includes("decision-required")) return null;
  if (i.assignees.length) return null;
  if (l.includes("deferred")) return "`deferred`; remove the label to queue it";
  if (!tierOf(l) && !l.includes("opus-plan"))
    return "no tier label; add `haiku`, `sonnet` or `opus` to queue it";
  if (l.includes("opus-plan"))
    return "`opus-plan`; start a plan session by hand";
  if (blockersOf.get(i.number).size) return blockedText(i.number);
};
const notPicked = [];
const ready = issues.filter((i) => {
  const why = skip(i);
  if (why)
    notPicked.push({ issue: i.number, title: i.title, url: i.html_url, why });
  return why === undefined && !FOLLOWUPS_ONLY;
});
const dispatches = ready
  .sort((a, b) => a.number - b.number)
  .map((i) => ({
    kind: "dispatch",
    issue: i.number,
    tier: tierOf(names(i)),
    title: `#${i.number} ${i.title}`,
    prompt: [
      `Implement #${i.number} (${i.html_url}) in ${REPO}, following CLAUDE.md.`,
      `Work on a new branch \`claude/issue-${i.number}\` from \`origin/main\` and push it.`,
      `Open a PR whose description fills in .github/pull_request_template.md: \`Fixes #${i.number}\`, the acceptance check re-run with before → after, and the build & lint result.`,
      tierOf(names(i)) === "opus"
        ? `Don't label the PR \`${AUTOMERGE}\`: it waits for the maintainer's review.`
        : `Label the PR \`${AUTOMERGE}\`: the dispatcher merges it once green.`,
      `Do not subscribe to PR activity: the daily dispatcher follows up on red CI and review comments.`,
    ].join("\n"),
  }));

// Claimed by a dispatch, still no PR: stuck.
for (const i of issues.filter(
  (i) => i.assignees.length && !linked.has(i.number),
)) {
  if (isDigest(i) || i.sub_issues_summary?.total > 0) continue;
  const mark = i.comments
    ? all(`repos/${REPO}/issues/${i.number}/comments?per_page=100`)
        .filter((c) => marked(c, DISPATCH))
        .at(-1)
    : null;
  if (!mark && tierOf(names(i)))
    notPicked.push({
      issue: i.number,
      title: i.title,
      url: i.html_url,
      why: `assigned to ${i.assignees.map((a) => `@${a.login}`).join(", ")}; unassign to queue it`,
    });
  else if (mark && days(mark.created_at) > STALE_DAYS)
    unstick.push({
      issue: i.number,
      title: i.title,
      url: i.html_url,
      why: `dispatched ${mark.created_at.slice(0, 10)}, no PR yet; unassign to re-dispatch`,
    });
}

// Follow-ups first: finishing beats starting.
const sessions = [...followups, ...dispatches].slice(0, MAX_SESSIONS);
const queue = dispatches.slice(Math.max(0, MAX_SESSIONS - followups.length));

// --- Survey parents ---------------------------------------------------------
// A survey run's parent closes once every finding is resolved; one whose open
// findings all wait on a decision (or are deferred) is not picked up, like any
// other stalled ticket.
const parents = issues.filter(
  (i) =>
    i.sub_issues_summary?.total > 0 &&
    names(i).some((l) => SURVEY_LABELS.includes(l)),
);
const closeParents = parents
  .filter((p) => p.sub_issues_summary.completed === p.sub_issues_summary.total)
  .map((p) => ({ issue: p.number, title: p.title }));
for (const p of parents.filter(
  (p) => p.sub_issues_summary.completed < p.sub_issues_summary.total,
)) {
  const open = all(
    `repos/${REPO}/issues/${p.number}/sub_issues?per_page=100`,
  ).filter((s) => s.state === "open");
  if (open.every((s) => names(s).some((l) => HELD.includes(l))))
    notPicked.push({
      issue: p.number,
      title: p.title,
      url: p.html_url,
      why: `survey run; its open findings wait on ${open.map((s) => `#${s.number}`).join(", ")}`,
    });
}

// --- Digest -----------------------------------------------------------------
// One issue per survey cycle. Its body is rewritten on every run (an edit
// notifies nobody); publishing it is the ping.
// A decision on a blocked issue can wait until its blocker is done.
const decide = [];
for (const i of issues.filter((i) => names(i).includes("decision-required"))) {
  const x = { issue: i.number, title: i.title, url: i.html_url };
  if (blockersOf.get(i.number).size)
    notPicked.push({ ...x, why: blockedText(i.number) });
  else decide.push(x);
}
// What finishing an ask frees: the open issues waiting on it (or, for a PR, on
// the issues it closes).
const unblocks = (x) => {
  const done = x.pr
    ? linkedIssues(prs.find((p) => p.number === x.pr))
    : [x.issue];
  return issues
    .filter((i) => done.some((n) => blockersOf.get(i.number).has(n)))
    .map((i) => `#${i.number}`);
};
const line = (x, ask) => {
  const why = [
    x.why,
    ...(ask && unblocks(x).length
      ? [`unblocks ${unblocks(x).join(", ")}`]
      : []),
  ]
    .filter(Boolean)
    .join("; ");
  return `- ${ask ? `[ ] **${ask}** ` : ""}[#${x.pr ?? x.issue}](${x.url}) ${x.title}${why ? ` (${why})` : ""}`;
};
const section = (h, xs, ask) =>
  xs.length ? [`## ${h}`, "", ...xs.map((x) => line(x, ask)), ""] : [];
const NOTE =
  "_The draft digest is rewritten by every daily run and published the day after each survey run (Tuesdays and Fridays). Answer on the issue or PR, or reply here: the next daily run copies replies onto their issues._\n\n";
// PRs first: they are finished work, and go stale while they wait.
const asks = [
  ...section("Review", review, "Review:"),
  ...section("Unstick", unstick, "Unstick:"),
  ...section("Decide", decide, "Decide:"),
];
// Issues that wait on another issue, a decision or the maintainer's own
// `deferred` would repeat in every digest, so they are only counted; what
// they wait on is listed above.
const isWaiting = (x) => /^(blocked by|`deferred`|survey run;)/.test(x.why);
const waiting = notPicked.filter(isWaiting);
const info = [
  ...section(
    "Queue (dispatched next, oldest first)",
    queue.map((q) => ({
      issue: q.issue,
      title: q.title.replace(/^#\d+ /, ""),
      url: `https://github.com/${REPO}/issues/${q.issue}`,
    })),
  ),
  ...section(
    "Not picked up",
    notPicked.filter((x) => !isWaiting(x)),
  ),
  ...(waiting.length
    ? [
        `<details><summary>${waiting.length} issues waiting on a blocker, a decision or <code>deferred</code></summary>`,
        "",
        ...waiting.map((x) => line(x)),
        "",
        "</details>",
        "",
      ]
    : []),
];
// The draft collects one survey cycle; at its end it is published (retitled, pinged)
// and the next draft opens. The previous published digest is then closed.
const isDraft = (i) => i.title.includes("(draft)");
const digests = issues.filter(isDigest).sort((a, b) => a.number - b.number);
const draft = digests.findLast(isDraft);
const published = digests.findLast((i) => !isDraft(i));
const marker = /<!-- digest-(?:date|since): (\S+) -->/;
const since =
  (draft ?? published)?.body?.match(marker)?.[1] ??
  new Date(TODAY - DIGEST_DAYS * 864e5).toISOString().slice(0, 10);
// What merged in this digest's window, each with the issue it closed and its labels.
const merged = api(
  "search/issues",
  "-X",
  "GET",
  "-f",
  `q=repo:${REPO} is:pr is:merged merged:>=${since}`,
  "-f",
  "per_page=100",
)
  .items.sort((a, b) => a.number - b.number)
  .map((pr) => {
    const closes = linkedIssues(pr).map(
      (n) => `#${n} · ${names(api(`repos/${REPO}/issues/${n}`)).join(", ")}`,
    );
    return `- [#${pr.number}](${pr.html_url}) ${pr.title}${closes.length ? ` (closes ${closes.join("; ")})` : ""}`;
  });
const render = (start, mergedLines, prev) =>
  `<!-- digest-since: ${start} -->\n\n${NOTE}${
    [...asks, ...info].join("\n") || "Nothing is waiting on the maintainer.\n"
  }${prev ? `\nPrevious digest: #${prev}.\n` : ""}${
    mergedLines.length
      ? `\n<details><summary>${mergedLines.length} merged since ${start.slice(0, 10)}</summary>\n\n${mergedLines.join("\n")}\n\n</details>\n`
      : ""
  }`.trim() + FOOTER;
const body = render(since, merged, published?.number);
// A quiet cycle (nothing merged, nothing to act on) stays a draft.
const publish =
  !FOLLOWUPS_ONLY &&
  !!draft &&
  days(since) >= DIGEST_DAYS &&
  DIGEST_WEEKDAYS.includes(new Date(NOW).getUTCDay()) &&
  (merged.length > 0 || asks.length > 0);
// Maintainer replies on either digest not yet copied onto their issues.
const replies = [draft, published].filter(Boolean).flatMap((d) => {
  const cs = all(`repos/${REPO}/issues/${d.number}/comments?per_page=100`);
  const relayedAt = cs.findLast((c) => marked(c, RELAYED))?.created_at ?? "";
  return cs
    .filter(
      (c) =>
        c.created_at > relayedAt &&
        c.user.type !== "Bot" &&
        !AGENT.test(c.body),
    )
    .map((c) => ({
      digest: d.number,
      url: c.html_url,
      author: c.user.login,
      body: c.body,
    }));
});
const digest = {
  draft: draft?.number ?? null,
  published: published?.number ?? null,
  publish,
  replies,
  counts: {
    decide: decide.length,
    review: review.length,
    unstick: unstick.length,
    queue: queue.length,
    notPicked: notPicked.length,
    merged: merged.length,
  },
};

// --- Apply ------------------------------------------------------------------
if (APPLY) {
  const me = api("user").login;
  // Every `automerge` PR already has finished, green CI, so merge it now,
  // pinned to the head commit that was checked. (GitHub refuses to *enable*
  // auto-merge on a PR that is already mergeable.) A refused merge is
  // logged and retried on the next run, not fatal.
  for (const m of automerge)
    try {
      post(
        `repos/${REPO}/pulls/${m.pr}/merge`,
        { sha: m.sha, merge_method: "merge" },
        "PUT",
      );
    } catch (e) {
      console.error(`merge #${m.pr} refused: ${e.stderr ?? e.message}`);
    }
  try {
    post(`repos/${REPO}/labels`, { name: AUTOMERGE, color: "0e8a16" });
  } catch {} // already exists
  for (const s of sessions) {
    if (s.kind === "dispatch") {
      post(`repos/${REPO}/issues/${s.issue}/assignees`, { assignees: [me] });
      const auto = s.tier !== "opus";
      post(`repos/${REPO}/issues/${s.issue}/comments`, {
        body: `${DISPATCH}\nDispatched by the daily pass to a ${s.tier} session. Its PR ${auto ? "gets" : "doesn't get"} \`${AUTOMERGE}\`: once green it ${auto ? "is merged by the next daily run" : "waits in the digest for your review"}. Add or remove the label on the PR to change that.${FOOTER}`,
      });
    } else {
      post(`repos/${REPO}/issues/${s.pr}/comments`, {
        body: `${FOLLOWUP}\nFollow-up session started for:\n${s.prompt
          .split("\n")
          .filter((l) => l.startsWith("- "))
          .join("\n")}${FOOTER}`,
      });
    }
  }
  for (const p of closeParents) {
    post(`repos/${REPO}/issues/${p.issue}/comments`, {
      body: `Every finding is resolved, so the daily pass closes this run.${FOOTER}`,
    });
    post(
      `repos/${REPO}/issues/${p.issue}`,
      { state: "closed", state_reason: "completed" },
      "PATCH",
    );
  }
  if (!FOLLOWUPS_ONLY) {
    const newDraft = (start, b) =>
      JSON.parse(
        post(`repos/${REPO}/issues`, {
          title: `${DIGEST_PREFIX} (draft) — from ${start.slice(0, 10)}`,
          body: b,
        }),
      ).number;
    const d = draft?.number ?? newDraft(since, body);
    if (draft && draft.body !== body)
      post(`repos/${REPO}/issues/${d}`, { body }, "PATCH");
    if (publish) {
      post(
        `repos/${REPO}/issues/${d}`,
        { title: `${DIGEST_PREFIX} — ${NOW.slice(0, 10)}` },
        "PATCH",
      );
      // A title or body edit notifies nobody; this comment is the ping.
      const { decide: x, review: r, unstick: u, merged: m } = digest.counts;
      post(`repos/${REPO}/issues/${d}/comments`, {
        body: `Published: ${r} to review, ${u} to unstick, ${x} to decide, ${m} merged.${FOOTER}`,
      });
      if (published) {
        post(`repos/${REPO}/issues/${published.number}/comments`, {
          body: `Superseded by #${d}.${FOOTER}`,
        });
        post(
          `repos/${REPO}/issues/${published.number}`,
          { state: "closed", state_reason: "completed" },
          "PATCH",
        );
      }
      digest.draft = newDraft(NOW, render(NOW, [], d));
      digest.published = d;
    }
  }
}

console.log(
  JSON.stringify(
    {
      applied: APPLY,
      sessions,
      automerge,
      closeParents,
      deferred: [...followups, ...dispatches]
        .slice(MAX_SESSIONS)
        .map((s) => s.title),
      digest: { ...digest, body },
    },
    null,
    2,
  ),
);
