#!/usr/bin/env node
// The farm's pause state and its two one-shot transitions. See docs/agents/farm-pause.md.
// Usage: node scripts/farm-pause.mjs [--apply] [--today YYYY-MM-DD]
// Prints {state, plan}. state is normal | drain | paused | resume. Without --apply
// nothing is written; with it, drain/resume carry out the plan and post their marker
// comment last, so a crash is retried and a second firing in the same state does nothing.
import { execFileSync } from "node:child_process";

const REPO = "realJohnDoe/meridian";
const arg = (name, dflt) => {
  const i = process.argv.indexOf(name);
  return i > 0 ? process.argv[i + 1] : dflt;
};
const APPLY = process.argv.includes("--apply");
const TODAY = arg("--today", new Date().toISOString().slice(0, 10));
const LABEL = "farm-paused";
const SNAPSHOT = "<!-- farm-snapshot -->";
const RESUMED = "<!-- farm-resumed -->";
const DRIFT = 100; // a deferred PR this many commits behind main is closed on resume
const FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_";
const TIERS = ["haiku", "sonnet", "opus", "opus-plan"];

const run = (cmd, args, input) =>
  execFileSync(cmd, args, { encoding: "utf8", input, maxBuffer: 1 << 26 });
const api = (path, ...rest) => JSON.parse(run("gh", ["api", path, ...rest]) || "null");
const all = (path) => api(path, "--paginate", "--slurp").flat();
const post = (path, body, method = "POST") =>
  run("gh", ["api", "-X", method, path, "--input", "-"], JSON.stringify(body));
const names = (x) => x.labels.map((l) => l.name);
const tiered = (x) => names(x).some((l) => TIERS.includes(l));
const ranking = () => run("node", ["scripts/survey-next.mjs"]).trim();

// --- State: one digest issue, its label and its marker comments --------------
const digest = all(`repos/${REPO}/issues?state=open&per_page=100`).find(
  (i) => !i.pull_request && i.title === "Farm digest",
);
if (!digest) {
  console.log(JSON.stringify({ state: "normal", plan: null }));
  process.exit(0);
}
const paused = names(digest).includes(LABEL);
const comments = all(`repos/${REPO}/issues/${digest.number}/comments?per_page=100`);
const snap = comments.findLast((c) => c.body.includes(SNAPSHOT));
const labeledAt = paused
  ? all(`repos/${REPO}/issues/${digest.number}/events?per_page=100`).findLast(
      (e) => e.event === "labeled" && e.label.name === LABEL,
    )?.created_at
  : null;
const resumed = snap && comments.some((c) => c.body.includes(RESUMED) && c.created_at > snap.created_at);
const state = paused
  ? snap && snap.created_at > labeledAt ? "paused" : "drain"
  : snap && !resumed ? "resume" : "normal";
if (state === "paused" || state === "normal") {
  console.log(JSON.stringify({ state, plan: null }));
  process.exit(0);
}

// --- Plan --------------------------------------------------------------------
const issues = all(`repos/${REPO}/issues?state=open&per_page=100`).filter((i) => !i.pull_request);
const prs = all(`repos/${REPO}/pulls?state=open&per_page=100`);
const closes = (pr) =>
  [...(pr.body ?? "").matchAll(/\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\s+#(\d+)/gi)].map((m) => Number(m[1]));
const linked = new Set(prs.flatMap(closes));
const pr_ = (p, why) => ({ pr: p.number, title: p.title, why });
const plan = {};

if (state === "drain") {
  // Run `farm-dispatch.mjs --apply --followups-only` first: it merges the green
  // PRs and gives red ones their last follow-up. Whatever is still red is deferred.
  plan.defer = [];
  for (const p of prs.filter((p) => !p.draft)) {
    const issue = closes(p).map((n) => issues.find((i) => i.number === n)).find((i) => i && tiered(i));
    if (!issue || [...names(p), ...names(issue)].includes("opus")) continue; // opus PRs stay open for review
    const runs = api(`repos/${REPO}/commits/${p.head.sha}/check-runs?per_page=100`).check_runs;
    const red = runs.some((r) => ["failure", "timed_out", "startup_failure"].includes(r.conclusion));
    const conflict = api(`repos/${REPO}/pulls/${p.number}`).mergeable === false;
    if (red || conflict) plan.defer.push(pr_(p, conflict ? "conflicts with main" : "CI red"));
  }
  plan.unassign = issues
    .filter((i) => tiered(i) && i.assignees.length && !linked.has(i.number))
    .map((i) => ({ issue: i.number, title: i.title }));
  plan.decisions = issues.filter((i) => names(i).includes("decision-required")).map((i) => i.number);
  plan.snapshot = [
    SNAPSHOT,
    `Farm paused ${TODAY}. Main at \`${api(`repos/${REPO}/commits/main`).sha}\`.`,
    `Deferred PRs: ${plan.defer.map((d) => `#${d.pr} (${d.why})`).join(", ") || "none"}.`,
    `Unassigned issues: ${plan.unassign.map((u) => `#${u.issue}`).join(", ") || "none"}.`,
    `Open decisions: ${plan.decisions.map((n) => `#${n}`).join(", ") || "none"}.`,
    `Survey ranking:\n\n\`\`\`\n${ranking()}\n\`\`\``,
  ].join("\n\n") + FOOTER;
} else {
  const deferred = prs.filter((p) => p.draft && names(p).includes("deferred"));
  plan.close = [];
  plan.undraft = [];
  for (const p of deferred) {
    const behind = api(`repos/${REPO}/compare/main...${p.head.label}`).behind_by;
    (behind > DRIFT ? plan.close : plan.undraft).push({ ...pr_(p, `${behind} commits behind main`), issues: closes(p) });
  }
  // Facts CLAUDE.md says go stale; the survey ranking decides where to start.
  let peer;
  try { peer = run("npm", ["view", "@typescript-eslint/typescript-estree@latest", "peerDependencies.typescript"]).trim(); }
  catch { peer = "lookup failed"; }
  plan.recheck = { tsEslintPeerRange: peer, surveyRanking: ranking() };
  plan.resumed = [
    RESUMED,
    `Farm resumed ${TODAY}.`,
    `Closed (drifted over ${DRIFT} commits, issues go back to the dispatcher): ${plan.close.map((c) => `#${c.pr}`).join(", ") || "none"}.`,
    `Back to ready: ${plan.undraft.map((c) => `#${c.pr}`).join(", ") || "none"}.`,
    `typescript-eslint peer range for typescript: \`${peer}\` (CLAUDE.md pin stands while its upper bound is below 7).`,
    `Fresh survey ranking:\n\n\`\`\`\n${plan.recheck.surveyRanking}\n\`\`\``,
  ].join("\n\n") + FOOTER;
}

// --- Apply -------------------------------------------------------------------
if (APPLY) {
  const note = (n, body) => post(`repos/${REPO}/issues/${n}/comments`, { body: body + FOOTER });
  if (state === "drain") {
    for (const d of plan.defer) {
      post(`repos/${REPO}/pulls/${d.pr}/ccr/convert_to_draft`, {});
      post(`repos/${REPO}/issues/${d.pr}/labels`, { labels: ["deferred"] });
      note(d.pr, `Deferred while the farm is paused: ${d.why}. It resumes on return.`);
    }
    for (const u of plan.unassign)
      post(`repos/${REPO}/issues/${u.issue}/assignees`, { assignees: api(`repos/${REPO}/issues/${u.issue}`).assignees.map((a) => a.login) }, "DELETE");
    post(`repos/${REPO}/issues/${digest.number}/comments`, { body: plan.snapshot });
  } else {
    for (const c of plan.close) {
      note(c.pr, `Closed on resume: ${c.why}. Its issue goes back to the dispatcher.`);
      post(`repos/${REPO}/pulls/${c.pr}`, { state: "closed" }, "PATCH");
      for (const n of c.issues) {
        const as = api(`repos/${REPO}/issues/${n}`).assignees.map((a) => a.login);
        if (as.length) post(`repos/${REPO}/issues/${n}/assignees`, { assignees: as }, "DELETE");
      }
    }
    for (const c of plan.undraft) {
      post(`repos/${REPO}/pulls/${c.pr}/ccr/ready_for_review`, {});
      post(`repos/${REPO}/issues/${c.pr}/labels/deferred`, {}, "DELETE");
    }
    post(`repos/${REPO}/issues/${digest.number}/comments`, { body: plan.resumed });
  }
}
console.log(JSON.stringify({ applied: APPLY, state, plan }, null, 2));
